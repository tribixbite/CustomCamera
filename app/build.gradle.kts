// ---------------------------------------------------------------------------
// Versioning: version.properties is the single source of truth.
// ---------------------------------------------------------------------------
val versionProps = Properties().apply {
    rootProject.file("version.properties").inputStream().use { load(it) }
}
val versionMajor = (versionProps["VERSION_MAJOR"] as String).toInt()
val versionMinor = (versionProps["VERSION_MINOR"] as String).toInt()
val versionPatch = (versionProps["VERSION_PATCH"] as String).toInt()

// Guard the place values so a field overflow cannot produce a versionCode
// lower than one already published (Play rejects downgrades).
require(versionMinor < 100 && versionPatch < 100) {
    "versionCode scheme overflow: MINOR ($versionMinor) and PATCH ($versionPatch) must be < 100"
}

// ---------------------------------------------------------------------------
// Release signing: read from keystore.properties (gitignored) or env vars.
// Without either, release builds fall back to the debug key with a warning so
// local `assembleRelease` still works; such an artifact must NOT be uploaded.
// ---------------------------------------------------------------------------
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.isFile) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    (keystoreProps[key] as String?) ?: System.getenv(env)

val releaseStoreFile = signingValue("storeFile", "CC_KEYSTORE_PATH")

android {
    namespace = "com.customcamera.app"
    compileSdk = libs.versions.compileSdk.get().toInt()

    defaultConfig {
        applicationId = "com.customcamera.app"
        minSdk = libs.versions.minSdk.get().toInt()
        targetSdk = libs.versions.targetSdk.get().toInt()
        versionCode = versionMajor * 10_000 + versionMinor * 100 + versionPatch
        versionName = "$versionMajor.$versionMinor.$versionPatch"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables.useSupportLibrary = true
    }

    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = rootProject.file(releaseStoreFile)
                storePassword = signingValue("storePassword", "CC_KEYSTORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "CC_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "CC_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            signingConfig = signingConfigs.findByName("release")
                ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        viewBinding = true
        buildConfig = true
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    packaging {
        resources {
            excludes += setOf(
                "/META-INF/{AL2.0,LGPL2.1}",
                "META-INF/version-control-info.textproto",
            )
        }
    }

    // Play requires an App Bundle; per-language/density/ABI splits are generated by Play.
    bundle {
        language { enableSplit = true }
        density { enableSplit = true }
        abi { enableSplit = true }
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

// Warn only when a release artifact is actually being produced without a real key.
gradle.taskGraph.whenReady {
    val buildingRelease = allTasks.any { it.name.contains("Release") && it.project == project }
    if (buildingRelease && releaseStoreFile == null) {
        logger.warn(
            "CustomCamera: no release keystore configured — the release build is signed " +
                "with the DEBUG key and must not be uploaded to Google Play."
        )
    }
}

